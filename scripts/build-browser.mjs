import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/browser/index.ts'],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2020',
  write: false,
});
mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/browser-bundle.ts',
  `// Generated by scripts/build-browser.mjs. Do not edit.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
